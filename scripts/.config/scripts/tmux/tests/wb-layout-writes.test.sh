#!/usr/bin/env bash
# Tests for U10: the dossier layout writers (`layout: dossier`) — record
# files, the shared handoff helper, `wb now`, `wb decide-supersede` and the
# generated views (wb_render_views) — plus the invariant that a task WITHOUT
# `layout: dossier` behaves exactly as before.
#
# Run in the Docker sandbox (see tests/Dockerfile):
#   docker run --rm -v "$(pwd)":/repo:ro -w /repo wb-tests \
#     bash scripts/.config/scripts/tmux/tests/wb-layout-writes.test.sh
set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WB="$SELF_DIR/wb.sh"

FIXTURE="$(mktemp -d -t wb-layout-writes-fixture.XXXXXX)"
trap 'rm -rf "$FIXTURE"' EXIT

fail=0
assert() { # <desc> <expected-regex> <actual>
  if printf '%s' "$3" | grep -qE "$2"; then echo "ok   - $1"
  else echo "FAIL - $1"; echo "       expected match: $2"; echo "       got: $(printf '%s' "$3" | head -8)"; fail=1; fi
}
assert_not() { # <desc> <regex> <actual>
  if printf '%s' "$3" | grep -qE "$2"; then echo "FAIL - $1"; echo "       unexpected match: $2"; fail=1
  else echo "ok   - $1"; fi
}
assert_eq() { # <desc> <expected> <actual>
  if [ "$2" = "$3" ]; then echo "ok   - $1"
  else echo "FAIL - $1 (expected '$2', got '$3')"; fail=1; fi
}

export XDG_STATE_HOME="$FIXTURE/state"
export HOME="$FIXTURE/home"
export CODE_DIR="$FIXTURE/code"
export TASKS_DIR="$FIXTURE/tasks"
mkdir -p "$XDG_STATE_HOME" "$HOME" "$CODE_DIR" "$TASKS_DIR"

# shellcheck disable=SC1090
source "$WB"
set +e

mk_layout_task() { # <stem> [extra frontmatter lines...]
  local stem="$1"; shift
  { printf -- '---\nstatus: doing\nrepo: proj\nbranch: b\nlayout: dossier\ntags: []\ncreated: 2026-07-01\nclosed:\n'
    for l in "$@"; do printf '%s\n' "$l"; done
    printf -- '---\n# Title\n\n## Plan\n\nplan text\n\n## Follow-ups\n\n## Decisions\n'
  } > "$TASKS_DIR/$stem.md"
}

# --- Decisions: record file + view; the old path is untouched ---------------
mk_layout_task proj--lay-a
A="$TASKS_DIR/proj--lay-a.md"
D="$TASKS_DIR/dossiers/proj--lay-a"
out="$(printf '### 2026-11-01 18:45 — Stage 0 Q3: Keep the Probe 6 board\n- Decided: keep it.\n- Why: it still works.\n' | cmd_append proj--lay-a Decisions - 2>&1)"; rc=$?
assert_eq "layout Decisions: exit 0" 0 "$rc"
F="$D/decisions/2026-11-01-1845-stage-0-q3-keep-the-probe-6-board.md"
if [ -f "$F" ]; then echo "ok   - layout Decisions: file named <ts>-<slug>.md"; else echo "FAIL - layout Decisions: expected $F, have: $(ls "$D/decisions" 2>&1)"; fail=1; fi
assert "decision file: status in-force" '^status: in-force$' "$(cat "$F" 2>/dev/null)"
assert "decision file: supersedes/superseded_by empty lists" '^supersedes: \[\]$' "$(cat "$F" 2>/dev/null)"
assert "decision file: title heading + body kept" '^# Stage 0 Q3: Keep the Probe 6 board$' "$(cat "$F" 2>/dev/null)"
assert "decision file: body bullets kept" '^- Why: it still works\.$' "$(cat "$F" 2>/dev/null)"
assert "decision file: frontmatter at byte 0" '^---$' "$(head -1 "$F" 2>/dev/null)"
assert "decisions.md lists it" 'Stage 0 Q3: Keep the Probe 6 board' "$(cat "$D/decisions.md" 2>/dev/null)"
assert "decisions.md: generated line first" '^<!-- generated by wb from dossiers/proj--lay-a/.*do not edit -->$' "$(head -1 "$D/decisions.md" 2>/dev/null)"
assert_not "task file gained no entry under ## Decisions" 'Keep the Probe 6' "$(cat "$A")"
assert "index.md written with the generated line" '^<!-- generated by wb from dossiers/proj--lay-a/' "$(head -1 "$D/index.md" 2>/dev/null)"

# same minute + same title -> -2
printf '### 2026-11-01 18:45 — Stage 0 Q3: Keep the Probe 6 board\nagain\n' | cmd_append proj--lay-a Decisions - >/dev/null 2>&1
if [ -f "${F%.md}-2.md" ]; then echo "ok   - same minute, same title: -2 suffix"; else echo "FAIL - -2 suffix missing: $(ls "$D/decisions")"; fail=1; fi
printf '### 2026-11-01 18:45 — Stage 0 Q3: Keep the Probe 6 board\nthird\n' | cmd_append proj--lay-a Decisions - >/dev/null 2>&1
if [ -f "${F%.md}-3.md" ]; then echo "ok   - third collision: -3 suffix"; else echo "FAIL - -3 suffix missing"; fail=1; fi

# no heading: now + first line as title; slug capped at 50
long="A very long decision title that certainly exceeds the fifty character slug limit by a lot"
printf '%s\nbody line\n' "$long" | cmd_append proj--lay-a Decisions - >/dev/null 2>&1
newest="$(ls "$D/decisions" | grep 'a-very-long' | head -1)"
assert "no heading: file named <now>-<slug>" '^[0-9]{4}-[0-9]{2}-[0-9]{2}-[0-9]{4}-a-very-long-decision-title' "$newest"
slugpart="${newest#????-??-??-????-}"; slugpart="${slugpart%.md}"
if [ "${#slugpart}" -le 50 ]; then echo "ok   - slug at most 50 chars (${#slugpart})"; else echo "FAIL - slug too long (${#slugpart})"; fail=1; fi

# --- Follow-ups ---------------------------------------------------------------
printf 'Check the migration on a store copy\n' | cmd_append proj--lay-a Follow-ups - >/dev/null 2>&1
OI="$(ls "$D/open-items" 2>/dev/null | head -1)"
assert "follow-up: open-items/<date>-<slug>.md" '^[0-9]{4}-[0-9]{2}-[0-9]{2}-check-the-migration-on-a-store-copy\.md$' "$OI"
assert "follow-up: since = today" "^since: $(date '+%Y-%m-%d')\$" "$(cat "$D/open-items/$OI" 2>/dev/null)"
assert "follow-up: status open" '^status: open$' "$(cat "$D/open-items/$OI" 2>/dev/null)"

# --- Old path: a task with no layout: byte-identical to today ----------------
OLD="$TASKS_DIR/proj--old.md"
printf -- '---\nstatus: doing\nrepo: proj\nbranch: o\ntags: []\ncreated: 2026-07-01\nclosed:\n---\n# Title\n\n## Decisions\n\n- earlier\n\n## Done\n' > "$OLD"
cp "$OLD" "$FIXTURE/old.expected"
cmd_append proj--old Decisions "### 2026-11-01 18:45 — x" >/dev/null 2>&1
_wb_append_under_heading "$FIXTURE/old.expected" Decisions "### 2026-11-01 18:45 — x"
if cmp -s "$OLD" "$FIXTURE/old.expected"; then echo "ok   - no layout: Decisions append byte-identical to _wb_append_under_heading"; else echo "FAIL - old path changed"; diff "$OLD" "$FIXTURE/old.expected" | head; fail=1; fi
assert "no layout: entry is under ## Decisions in the file" '^### 2026-11-01 18:45 — x$' "$(cat "$OLD")"
[ ! -d "$TASKS_DIR/dossiers/proj--old" ] && echo "ok   - no layout: no dossier created" || { echo "FAIL - no layout: dossier created"; fail=1; }
# the helper alone, on a layout-less file, for the auto-handoff path
cp "$OLD" "$FIXTURE/old2.md"; cp "$OLD" "$FIXTURE/old2.expected"
wb_append_handoff "$FIXTURE/old2.md" "wb pause" "msg"
_wb_append_under_heading "$FIXTURE/old2.expected" Handoffs "### $(date '+%Y-%m-%d %H:%M') — wb pause (auto)"$'\n\n'"msg"
if cmp -s "$FIXTURE/old2.md" "$FIXTURE/old2.expected"; then echo "ok   - no layout: wb_append_handoff byte-identical"; else echo "FAIL - wb_append_handoff old path changed"; fail=1; fi

# --- Other headings on a layout task: unchanged --------------------------------
cmd_append proj--lay-a Plan "extra plan line" >/dev/null 2>&1
assert "layout task, heading Plan: appended under ## Plan as before" 'extra plan line' "$(cat "$A")"

# --- decide-supersede ----------------------------------------------------------
mk_layout_task proj--lay-s
S="$TASKS_DIR/proj--lay-s.md"; SD="$TASKS_DIR/dossiers/proj--lay-s"
printf '### 2026-10-17 10:00 — Probe 6: delete the board\n- Decided: delete.\n' | cmd_append proj--lay-s Decisions - >/dev/null 2>&1
OLDID="2026-10-17-1000-probe-6-delete-the-board"
out="$(printf '### 2026-10-17 16:00 — Step back from deleting the board\n- Why: still needed.\n' | cmd_decide_supersede proj--lay-s "$OLDID" - 2>&1)"; rc=$?
assert_eq "decide-supersede: exit 0" 0 "$rc"
NEWID="2026-10-17-1600-step-back-from-deleting-the-board"
assert "supersede: new file supersedes the old id" "^supersedes: \[$OLDID\]\$" "$(cat "$SD/decisions/$NEWID.md" 2>/dev/null)"
assert "supersede: old file status superseded" '^status: superseded$' "$(cat "$SD/decisions/$OLDID.md")"
assert "supersede: old file superseded_by new" "^superseded_by: \[$NEWID\]\$" "$(cat "$SD/decisions/$OLDID.md")"
assert "supersede: old file body untouched" '^- Decided: delete\.$' "$(cat "$SD/decisions/$OLDID.md")"
assert "decisions.md: superseded collapsed under its own heading" '^## Superseded \(1\)$' "$(cat "$SD/decisions.md")"
l_force="$(grep -n '^## In force' "$SD/decisions.md" | cut -d: -f1)"; l_sup="$(grep -n '^## Superseded' "$SD/decisions.md" | cut -d: -f1)"
if [ -n "$l_force" ] && [ -n "$l_sup" ] && [ "$l_force" -lt "$l_sup" ]; then echo "ok   - decisions.md: in force before superseded"; else echo "FAIL - decisions.md ordering"; fail=1; fi
snap="$(cd "$SD" && find . -type f | LC_ALL=C sort | xargs cat | md5sum)"
out="$(printf 'again\n' | cmd_decide_supersede proj--lay-s "$OLDID" - 2>&1)"; rc=$?
assert_eq "supersede already-superseded: exit 1" 1 "$rc"
out="$(printf 'again\n' | cmd_decide_supersede proj--lay-s "no-such-id" - 2>&1)"; rc=$?
assert_eq "supersede unknown id: exit 1" 1 "$rc"
snap2="$(cd "$SD" && find . -type f | LC_ALL=C sort | xargs cat | md5sum)"
assert_eq "refused supersedes wrote nothing" "$snap" "$snap2"

# --- Handoffs: wb_append_handoff and wb append Handoffs ------------------------
check_handoffs() { # <label> <task file> <dossier dir>
  local label="$1" tf="$2" dd="$3"
  assert_eq "$label: one handoff heading left in the task file" 1 "$(grep -c '^### ' "$tf")"
  assert_eq "$label: two files in handoffs/" 2 "$(find "$dd/handoffs" -maxdepth 1 -name '*.md' | wc -l | tr -d ' ')"
  assert "$label: handoffs.md written" '^# Handoffs' "$(cat "$dd/handoffs.md" 2>/dev/null)"
  local first second
  first="$(grep -n '^## ' "$dd/handoffs.md" | sed -n 1p | cut -d: -f2)"; second="$(grep -n '^## ' "$dd/handoffs.md" | sed -n 2p | cut -d: -f2)"
  if [[ "$first" > "$second" ]]; then echo "ok   - $label: handoffs.md newest first"; else echo "FAIL - $label: order '$first' then '$second'"; fail=1; fi
}
mk_layout_task proj--lay-h
H="$TASKS_DIR/proj--lay-h.md"; HD="$TASKS_DIR/dossiers/proj--lay-h"
# distinct minutes: the auto stamp uses `date`, so fake it with explicit headings via wb_handoff_write
wb_handoff_write "$H" $'### 2026-11-01 10:00 — wb pause (auto)\n\nfirst'
wb_handoff_write "$H" $'### 2026-11-01 11:00 — wb resume (auto)\n\nsecond'
wb_handoff_write "$H" $'### 2026-11-01 12:00 — wb done (auto)\n\nthird'
check_handoffs "wb_handoff_write x3" "$H" "$HD"
assert "newest stays in the task file" '^third$' "$(cat "$H")"
assert "moved file carries source/auto" '^auto: true$' "$(cat "$HD/handoffs/2026-11-01-1000.md")"
assert "moved file carries source" '^source: wb pause$' "$(cat "$HD/handoffs/2026-11-01-1000.md")"
# the real wb_append_handoff, three calls in one minute: names collide -> -2
mk_layout_task proj--lay-h2
H2="$TASKS_DIR/proj--lay-h2.md"; H2D="$TASKS_DIR/dossiers/proj--lay-h2"
wb_append_handoff "$H2" "wb pause" "one"; wb_append_handoff "$H2" "wb resume" "two"; wb_append_handoff "$H2" "wb done" "three"
assert_eq "wb_append_handoff x3: one handoff heading in task file" 1 "$(grep -c '^### ' "$H2")"
assert_eq "wb_append_handoff x3: two files in handoffs/" 2 "$(find "$H2D/handoffs" -maxdepth 1 -name '*.md' | wc -l | tr -d ' ')"
assert "wb_append_handoff x3: newest message in the task file" '^three$' "$(cat "$H2")"
assert "wb_append_handoff x3: handoffs.md lists both" 'two' "$(cat "$H2D/handoffs.md")"
# /wb-save path
mk_layout_task proj--lay-h3
H3="$TASKS_DIR/proj--lay-h3.md"; H3D="$TASKS_DIR/dossiers/proj--lay-h3"
printf '### 2026-11-01 10:00 — wb-save\n**Done:** a\n**Next:** b\n' | cmd_append proj--lay-h3 Handoffs - >/dev/null 2>&1
printf '### 2026-11-01 11:00 — wb-save\n**Done:** c\n**Next:** d\n' | cmd_append proj--lay-h3 Handoffs - >/dev/null 2>&1
printf '### 2026-11-01 12:00 — wb-save\n**Done:** e\n**Next:** f\n' | cmd_append proj--lay-h3 Handoffs - >/dev/null 2>&1
check_handoffs "wb append Handoffs x3" "$H3" "$H3D"
assert "wb-save: the newest block is in the task file" '^\*\*Done:\*\* e$' "$(cat "$H3")"
assert "wb-save: moved file has auto: false" '^auto: false$' "$(cat "$H3D/handoffs/2026-11-01-1100.md")"
# a task file with several handoffs (pre-migration) ends with exactly one
mk_layout_task proj--lay-h4
H4="$TASKS_DIR/proj--lay-h4.md"
printf '\n## Handoffs\n\n### 2026-10-01 09:00 — wb pause (auto)\n\nold one\n\n### 2026-10-02 09:00 — wb pause (auto)\n\nold two\n' >> "$H4"
wb_handoff_write "$H4" $'### 2026-11-01 12:00 — wb-save\nnew'
assert_eq "several existing handoffs: exactly one remains in the task file" 1 "$(grep -c '^### ' "$H4")"
assert_eq "several existing handoffs: both moved out" 2 "$(find "$TASKS_DIR/dossiers/proj--lay-h4/handoffs" -name '*.md' | wc -l | tr -d ' ')"

# --- wb now -------------------------------------------------------------------
NOW="$TASKS_DIR/proj--now.md"
printf -- '---\nstatus: doing\nrepo: proj\nlayout: dossier\n---\n# Title\n\n## Now\n\nold goal\nold next\n\n## Plan\n\nplan text\n\n## Handoffs\n\nh\n' > "$NOW"
cp "$NOW" "$FIXTURE/now.before"
printf 'new goal\nnew next\n' | cmd_now proj--now - >/dev/null 2>&1
expected="$(sed -e 's/^old goal$/new goal/' -e 's/^old next$/new next/' "$FIXTURE/now.before")"
assert_eq "wb now: only the Now block changed" "$expected" "$(cat "$NOW")"
printf '## Now\nwith heading\n' | cmd_now proj--now - >/dev/null 2>&1
assert_eq "wb now: a leading '## Now' line is not duplicated" 1 "$(grep -c '^## Now$' "$NOW")"
NONOW="$TASKS_DIR/proj--nonow.md"
printf -- '---\nstatus: doing\nrepo: proj\n---\n# Title\n\n## Plan\n\nplan text\n' > "$NONOW"
printf 'goal here\n' | cmd_now proj--nonow - >/dev/null 2>&1
assert_eq "wb now: no ## Now -> inserted below the title, above the first section" "---
status: doing
repo: proj
---
# Title

## Now

goal here

## Plan

plan text" "$(cat "$NONOW")"
printf 'goal two\n' | cmd_now proj--nonow - >/dev/null 2>&1
assert_eq "wb now: second call replaces, does not duplicate" 1 "$(grep -c '^## Now$' "$NONOW")"
assert "wb now: second call body" '^goal two$' "$(cat "$NONOW")"
assert "wb now: title and plan survive the replace" '^# Title$' "$(cat "$NONOW")"
NOSEC="$TASKS_DIR/proj--nosec.md"
printf -- '---\nstatus: doing\n---\n# Title\n\nintro line\n' > "$NOSEC"
printf 'goal\n' | cmd_now proj--nosec - >/dev/null 2>&1
assert_eq "wb now: no sections at all -> appended at EOF" "---
status: doing
---
# Title

intro line

## Now

goal" "$(cat "$NOSEC")"
FMH="$TASKS_DIR/proj--fmh.md"
printf -- '---\nstatus: doing\nnote: |\n\n## Now\n---\n# Title\n\n## Plan\n\np\n' > "$FMH"
printf 'goal\n' | cmd_now proj--fmh - >/dev/null 2>&1
assert_eq "wb now: a heading-shaped line inside the frontmatter is never matched" 2 "$(grep -c '^## Now$' "$FMH")"
# a dozen saves keep the file small (AE9)
for i in 1 2 3 4 5 6 7 8; do
  printf '### 2026-11-01 1%d:00 — wb-save\n**Done:** x\n**Next:** y\n' "$i" | cmd_append proj--lay-h3 Handoffs - >/dev/null 2>&1
  printf 'goal %d\n' "$i" | cmd_now proj--lay-h3 - >/dev/null 2>&1
done
if [ "$(wc -l < "$H3")" -lt 40 ]; then echo "ok   - task file stays under 40 lines after many saves ($(wc -l < "$H3"))"; else echo "FAIL - task file grew to $(wc -l < "$H3") lines"; fail=1; fi

# --- views: deterministic under gawk and mawk; index grouping -------------------
mk_layout_task proj--lay-i
I="$TASKS_DIR/proj--lay-i.md"; ID="$TASKS_DIR/dossiers/proj--lay-i"
sed -i 's/^parent:.*//' "$I"
printf -- '---\nstatus: doing\nrepo: proj\nlayout: dossier\n---\n# Parent\n' > "$I"
mkdir -p "$ID" "$TASKS_DIR/dossiers/proj--lay-i-kid"
printf -- '---\ntags: [plan]\nrung: 1\n---\n# The Spec\n' > "$ID/spec.md"
printf -- '---\ntags: [guide, ops]\n---\n# Ops guide\n' > "$ID/ops.md"
printf -- '---\ntags: []\nretire_when: decision:zzz-ready recorded\n---\n# Old test guide\n' > "$ID/old-guide.md"
printf -- '---\ntags: [guide]\nretire_when: pr:5 merged\n---\n# PR-gated guide\n' > "$ID/prgated.md"
printf '<!--\n---\ntags: [diagram]\n---\n-->\n<title>Arch picture</title>\n' > "$ID/arch.html"
printf 'untagged page\n' > "$ID/plain.md"
mkdir -p "$ID/decisions"; printf -- '---\nstatus: in-force\nsupersedes: []\nsuperseded_by: []\nreview_at:\n---\n# Ready\n\nbody\n' > "$ID/decisions/zzz-ready.md"
printf -- '---\nstatus: doing\nrepo: proj\nparent: proj--lay-i\n---\n# Kid\n' > "$TASKS_DIR/proj--lay-i-kid.md"
printf -- '---\ntags: [notes]\n---\n# Kid notes\n' > "$TASKS_DIR/dossiers/proj--lay-i-kid/kidnotes.md"

AWKDIR="$FIXTURE/awkshim"
for flavour in gawk mawk; do
  real="$(command -v "$flavour" || true)"
  if [ -z "$real" ]; then echo "FAIL - $flavour not installed in the sandbox"; fail=1; continue; fi
  rm -rf "$AWKDIR"; mkdir -p "$AWKDIR"; ln -s "$real" "$AWKDIR/awk"
  (
    PATH="$AWKDIR:$PATH"
    hash -r
    wb_render_views "$I"
    a="$(cd "$ID" && cat index.md decisions.md | md5sum)"
    wb_render_views "$I"
    b="$(cd "$ID" && cat index.md decisions.md | md5sum)"
    [ "$a" = "$b" ] && echo "ok   - views identical on a re-run ($flavour)" || { echo "FAIL - views changed on re-run ($flavour)"; exit 1; }
    # also no mtime churn on an unchanged view
    m1="$(stat -c %Y "$ID/index.md")"; sleep 1; wb_render_views "$I"; m2="$(stat -c %Y "$ID/index.md")"
    [ "$m1" = "$m2" ] && echo "ok   - unchanged view not rewritten ($flavour)" || { echo "FAIL - view rewritten ($flavour)"; exit 1; }
    # supersede + handoff views under this awk
    cp "$ID/index.md" "$FIXTURE/index.$flavour"
    exit 0
  ) || fail=1
done
if cmp -s "$FIXTURE/index.gawk" "$FIXTURE/index.mawk" 2>/dev/null; then echo "ok   - index.md identical under gawk and mawk"; else echo "FAIL - index.md differs between gawk and mawk"; diff "$FIXTURE/index.gawk" "$FIXTURE/index.mawk" | head; fail=1; fi

IDX="$(cat "$ID/index.md")"
assert "index: first line generated marker" '^<!-- generated by wb from dossiers/proj--lay-i/' "$(head -1 "$ID/index.md")"
l_pin="$(grep -n '^## Plans and specs' "$ID/index.md" | cut -d: -f1)"; l_guide="$(grep -n '^## guide' "$ID/index.md" | cut -d: -f1)"
if [ -n "$l_pin" ] && [ -n "$l_guide" ] && [ "$l_pin" -lt "$l_guide" ]; then echo "ok   - index: plans/specs pinned first"; else echo "FAIL - index: pinned group not first (pin=$l_pin guide=$l_guide)"; fail=1; fi
assert "index: spec page under the pinned group" '\[The Spec\]\(spec\.md\)' "$IDX"
assert "index: page grouped by tag (ops)" '^## ops$' "$IDX"
assert "index: multi-tag page listed under both tags" 'Ops guide' "$IDX"
assert "index: html page with comment frontmatter grouped by its tag" '^## diagram$' "$IDX"
assert "index: untagged page under Other" '^## Other$' "$IDX"
assert "index: retired page behind one link" '^## Retired \(1\)$' "$IDX"
retired_block="$(awk '/^## Retired/{f=1} f' "$ID/index.md")"
assert "index: the retire_when-matched page is in the retired block" 'Old test guide' "$retired_block"
assert_not "index: retired page not in the current groups" 'Old test guide' "$(awk '/^## Retired/{exit} {print}' "$ID/index.md")"
assert "index: pr: trigger not evaluated, page stays current" 'PR-gated guide' "$(awk '/^## Retired/{exit} {print}' "$ID/index.md")"
assert "index: child's pages listed under the child" '^### proj--lay-i-kid$' "$IDX"
assert "index: child page link goes through the child's dossier" '\(\.\./proj--lay-i-kid/kidnotes\.md\)' "$IDX"

# --- concurrency: two shells appending to one layout task -----------------------
mk_layout_task proj--lay-c
CD="$TASKS_DIR/dossiers/proj--lay-c"
( printf '### 2026-11-01 09:00 — Concurrent one\nx\n' | bash "$WB" append proj--lay-c Decisions - >/dev/null 2>&1 ) &
p1=$!
( printf '### 2026-11-01 09:00 — Concurrent two\ny\n' | bash "$WB" append proj--lay-c Decisions - >/dev/null 2>&1 ) &
p2=$!
wait "$p1" "$p2"
n="$(find "$CD/decisions" -name '*.md' | wc -l | tr -d ' ')"
# one of the two may legitimately lose the lock (exit 75) rather than wait; retry that one serially
if [ "$n" != 2 ]; then
  [ -f "$CD/decisions/2026-11-01-0900-concurrent-one.md" ] || printf '### 2026-11-01 09:00 — Concurrent one\nx\n' | bash "$WB" append proj--lay-c Decisions - >/dev/null 2>&1
  [ -f "$CD/decisions/2026-11-01-0900-concurrent-two.md" ] || printf '### 2026-11-01 09:00 — Concurrent two\ny\n' | bash "$WB" append proj--lay-c Decisions - >/dev/null 2>&1
  echo "note - one concurrent writer reported lock contention and was retried"
fi
assert_eq "concurrent appends: two decision files" 2 "$(find "$CD/decisions" -name '*.md' | wc -l | tr -d ' ')"
assert "concurrent appends: view lists both (one)" 'Concurrent one' "$(cat "$CD/decisions.md")"
assert "concurrent appends: view lists both (two)" 'Concurrent two' "$(cat "$CD/decisions.md")"

# --- wb help ---------------------------------------------------------------------
help="$(cmd_help)"
assert "wb help lists now" '^  wb now ' "$help"
assert "wb help lists decide-supersede" '^  wb decide-supersede ' "$help"

echo
[ "$fail" -eq 0 ] && echo "ALL PASS" || echo "FAILURES"
exit "$fail"
