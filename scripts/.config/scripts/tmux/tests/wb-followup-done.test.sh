#!/usr/bin/env bash
# Tests for `wb followups <task>` and `wb followup-done <task> <ref> [<note>|-]`:
# listing a task's OPEN follow-ups and marking one done, on a layout task
# (open-items/ record: status: closed + closed: <date>, views rebuilt) and an
# old-layout task (the bullet becomes `- [x] <text>`). Covers the ref rules
# (exact id/index, else a unique case-insensitive substring), an ambiguous ref,
# no match, an already-closed item, the note, and the counts dropping.
#
# Run in the Docker sandbox (see tests/Dockerfile):
#   docker run --rm -v "$(pwd)":/repo:ro -w /repo wb-tests \
#     bash scripts/.config/scripts/tmux/tests/wb-followup-done.test.sh
set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WB="$SELF_DIR/wb.sh"

FIXTURE="$(mktemp -d -t wb-followup-done-fixture.XXXXXX)"
trap 'rm -rf "$FIXTURE"' EXIT

fail=0
assert() { # <desc> <expected-regex> <actual>
  if printf '%s' "$3" | grep -qE "$2"; then echo "ok   - $1"
  else echo "FAIL - $1"; echo "       expected match: $2"; echo "       got: $(printf '%s' "$3" | head -8)"; fail=1; fi
}
assert_not() { # <desc> <regex> <actual>
  if printf '%s' "$3" | grep -qE "$2"; then echo "FAIL - $1"; echo "       unexpected match: $2"; fail=1
  else echo "ok   - $1"; fi
}
assert_eq() { # <desc> <expected> <actual>
  if [ "$2" = "$3" ]; then echo "ok   - $1"
  else echo "FAIL - $1 (expected '$2', got '$3')"; fail=1; fi
}

export XDG_STATE_HOME="$FIXTURE/state"
export HOME="$FIXTURE/home"
export CODE_DIR="$FIXTURE/code"
export TASKS_DIR="$FIXTURE/tasks"
mkdir -p "$XDG_STATE_HOME" "$HOME" "$CODE_DIR" "$TASKS_DIR"
unset TMUX

# shellcheck disable=SC1090
source "$WB"
set +e

TODAY="$(date '+%Y-%m-%d')"

# --- layout task -----------------------------------------------------------------
{ printf -- '---\nstatus: doing\nrepo: proj\nbranch: b\nlayout: dossier\ntags: []\ncreated: 2026-07-01\nclosed:\n---\n# Title\n\n## Plan\n\nplan text\n'; } > "$TASKS_DIR/proj--lay.md"
printf -- '- [ ] Rotate the staging keys\n- [ ] Rewrite the retry loop\n  - with a detail\n- plain: Tidy the logs\n- [ ] Rotate the prod keys\n' | cmd_append proj--lay Follow-ups - > /dev/null 2>&1
D="$TASKS_DIR/dossiers/proj--lay"
out="$(cmd_followups proj--lay 2>&1)"; rc=$?
assert_eq "layout followups: exit 0" 0 "$rc"
assert_eq "layout followups: four open lines" 4 "$(printf '%s\n' "$out" | wc -l | tr -d ' ')"
assert "layout followups: <id><TAB><title>" $'^[0-9]{4}-[0-9]{2}-[0-9]{2}-rewrite-the-retry-loop\tRewrite the retry loop$' "$out"
assert_eq "layout: open count before" 4 "$(wb_followup_count)"

# ambiguous substring: two items match "keys"
out="$(cmd_followup_done proj--lay keys 2>&1)"; rc=$?
assert_eq "layout: ambiguous ref exits 1" 1 "$rc"
assert "layout: ambiguous ref lists the staging candidate" 'rotate-the-staging-keys' "$out"
assert "layout: ambiguous ref lists the prod candidate" 'rotate-the-prod-keys' "$out"
assert_eq "layout: nothing changed by the ambiguous call" 4 "$(_wb_open_items "$TASKS_DIR/proj--lay.md" | wc -l | tr -d ' ')"
out="$(cmd_followup_done proj--lay "no such thing" 2>&1)"; rc=$?
assert_eq "layout: no match exits 1" 1 "$rc"
assert "layout: no match says so" 'no open follow-up matches' "$out"

# a unique, case-insensitive substring of the title, with a note
out="$(cmd_followup_done proj--lay "RETRY loop" "fixed in #12" 2>&1)"; rc=$?
assert_eq "layout: unique substring exits 0" 0 "$rc"
F="$(ls "$D"/open-items/*-rewrite-the-retry-loop.md)"
assert "layout: status closed" '^status: closed$' "$(cat "$F")"
assert "layout: closed: <today> in the frontmatter" "^closed: $TODAY\$" "$(sed -n '1,/^---$/p;' "$F"; sed -n '2,8p' "$F")"
assert "layout: the note is appended as a Closed line" "^Closed $TODAY: fixed in #12\$" "$(cat "$F")"
assert "layout: body kept" 'with a detail' "$(cat "$F")"
assert_eq "layout: frontmatter still opens at byte 0 and has one status line" 1 "$(grep -c '^status:' "$F")"
assert_eq "layout: open count dropped" 3 "$(wb_followup_count)"
assert_not "layout: the closed item is no longer listed" 'retry' "$(cmd_followups proj--lay 2>&1)"
assert "layout: views rebuilt (index.md present, generated line)" '^<!-- generated by wb' "$(head -1 "$D/index.md" 2>/dev/null)"

# already closed
out="$(cmd_followup_done proj--lay "retry loop" 2>&1)"; rc=$?
assert_eq "layout: already-closed item exits 1" 1 "$rc"
assert "layout: already-closed message" 'already done' "$out"

# exact id, no note: no Closed line
ID="$(cmd_followups proj--lay | grep 'Tidy the logs' | cut -f1)"
out="$(cmd_followup_done proj--lay "$ID" 2>&1)"; rc=$?
assert_eq "layout: exact id exits 0" 0 "$rc"
assert_not "layout: no note, no Closed line" '^Closed ' "$(cat "$D/open-items/$ID.md")"
assert_eq "layout: open count after two closed" 2 "$(wb_followup_count)"
# note from stdin
echo "from stdin" | cmd_followup_done proj--lay "staging keys" - > /dev/null 2>&1
assert "layout: note read from stdin with '-'" "^Closed $TODAY: from stdin\$" "$(cat "$D"/open-items/*staging-keys.md)"

# --- old-layout task ---------------------------------------------------------------
{ printf -- '---\nstatus: doing\nrepo: proj\nbranch: b\ntags: []\ncreated: 2026-07-01\nclosed:\n---\n# Old\n\n## Plan\n\nplan text\n\n## Follow-ups\n\n'
  printf -- '- [ ] Alpha thing\n- Beta plain thing\n  - detail under beta\n- [x] Gamma already ticked\n* Delta star thing\n\n## Decisions\n\n- not a follow-up\n'
} > "$TASKS_DIR/proj--old.md"
out="$(cmd_followups proj--old 2>&1)"
assert_eq "old followups: three open (ticked one skipped)" $'1\tAlpha thing\n2\tBeta plain thing\n3\tDelta star thing' "$out"
OLDCOUNT_BEFORE="$(wb_followup_count)"
out="$(cmd_followup_done proj--old 2 "shipped" 2>&1)"; rc=$?
assert_eq "old: index ref exits 0" 0 "$rc"
assert "old: bullet ticked with the note" "^- \[x\] Beta plain thing — done $TODAY: shipped\$" "$(cat "$TASKS_DIR/proj--old.md")"
assert "old: continuation line stays" '^  - detail under beta$' "$(cat "$TASKS_DIR/proj--old.md")"
assert "old: other bullets unchanged" '^- \[ \] Alpha thing$' "$(cat "$TASKS_DIR/proj--old.md")"
assert "old: ## Decisions untouched" '^- not a follow-up$' "$(cat "$TASKS_DIR/proj--old.md")"
assert_eq "old: open count dropped by one" "$((OLDCOUNT_BEFORE - 1))" "$(wb_followup_count)"
assert_eq "old: indexes renumber over the open bullets" $'1\tAlpha thing\n2\tDelta star thing' "$(cmd_followups proj--old 2>&1)"
out="$(cmd_followup_done proj--old "beta" 2>&1)"; rc=$?
assert_eq "old: already-ticked item exits 1" 1 "$rc"
assert "old: already-ticked message" 'already done' "$out"
out="$(cmd_followup_done proj--old "thing" 2>&1)"; rc=$?
assert_eq "old: ambiguous substring exits 1" 1 "$rc"
assert "old: ambiguous lists candidates" 'Alpha thing' "$out"
out="$(cmd_followup_done proj--old "delta" 2>&1)"; rc=$?
assert_eq "old: unique substring exits 0" 0 "$rc"
assert "old: star bullet becomes '- [x]' with no note suffix" '^- \[x\] Delta star thing$' "$(cat "$TASKS_DIR/proj--old.md")"
cmd_followup_done proj--old 1 > /dev/null 2>&1
assert "old: checkbox bullet ticked" '^- \[x\] Alpha thing$' "$(cat "$TASKS_DIR/proj--old.md")"
assert_eq "old: no open follow-ups left" "" "$(cmd_followups proj--old 2>&1)"

# --- usage and dispatch --------------------------------------------------------------
out="$(bash "$WB" followup-done 2>&1)"; rc=$?
assert_eq "no argument: exit 1" 1 "$rc"
assert "no argument: usage" 'usage: wb followup-done' "$out"
assert "dispatch: wb followups runs" 'Rotate the prod keys' "$(bash "$WB" followups proj--lay 2>&1)"
assert "wb help lists followups" '^  wb followups ' "$(cmd_help)"
assert "wb help lists followup-done" '^  wb followup-done ' "$(cmd_help)"

echo
[ "$fail" -eq 0 ] && echo "ALL PASS" || echo "FAILURES"
exit "$fail"
